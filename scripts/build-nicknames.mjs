/**
 * Generate `src/lib/rrc/nicknames.generated.ts` from `data/nicknames.csv`.
 *
 * Run: node scripts/build-nicknames.mjs
 *
 * WHY GENERATED, not read at runtime. The matcher runs inside a server action on
 * the onboarding path, and a file read there means the CSV has to survive the
 * Vercel bundle (the geology corpus needed explicit config to do exactly that).
 * A generated module is bundled by the compiler for free and costs one import.
 *
 * WHY TWO MAPS AND NOT EQUIVALENCE GROUPS. The obvious implementation is
 * union-find over the pairs, giving each name a group id and making the test an
 * equality check. It is wrong, and quietly: the relation is not transitive.
 * `john -> jack` and `jackson -> jack` are both in the source, so the transitive
 * closure puts John and Jackson in one group, and from there the chain runs on
 * through every shared diminutive until Robert, William, Bill and Bob are all
 * the same person. Measured on this CSV: 2,252 names collapse into 314 groups,
 * one of which holds bill, bob, jack, john, robert and william.
 *
 * So the relation stays directed, and a match is one of three bounded tests:
 * exact, one hop in either direction, or a shared formal parent (jim and jimmy
 * are both James). One hop, never a closure.
 *
 * Source: https://github.com/carltonnorthern/nicknames (Apache-2.0).
 * The CSV and its licence are vendored under `data/`; re-run this after
 * refreshing them.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSV = path.join(ROOT, "data", "nicknames.csv");
const OUT = path.join(ROOT, "src", "lib", "rrc", "nicknames.generated.ts");

/**
 * Every pair, symmetric. `bill` and `william` are adjacent regardless of which
 * way the source happened to record it.
 */
const edges = new Map();
/**
 * Diminutive -> formal, and ONLY where the source's direction is credible.
 *
 * The CSV is not consistently directed: it carries `robert has_nickname bob` AND
 * `bill has_nickname robert`, the second of which is backwards. Taken at face
 * value, `robert` and `william` end up sharing the "parents" `bill` and `billy`,
 * and a shared-parent rule then declares Robert and William the same name. The
 * pruning heuristic is that a diminutive is not longer than the name it stands
 * for, which drops the reversed rows and leaves the real ones (`james -> jim`,
 * `margaret -> peggy`).
 *
 * Only the shared-parent test uses this map. Direct adjacency uses `edges`, so
 * the pruning cannot cost us a pair the source states outright.
 */
const parents = new Map();

const add = (map, key, value) => {
  const set = map.get(key) ?? new Set();
  set.add(value);
  map.set(key, set);
};

const rows = readFileSync(CSV, "utf8").split("\n").slice(1);
let pairs = 0;
let pruned = 0;
for (const row of rows) {
  const [rawFormal, rel, rawNick] = row.trim().split(",");
  if (!rawFormal || !rawNick || rel !== "has_nickname") continue;
  const formal = rawFormal.toLowerCase();
  const nick = rawNick.toLowerCase();
  add(edges, formal, nick);
  add(edges, nick, formal);
  if (nick.length <= formal.length) add(parents, nick, formal);
  else pruned++;
  pairs++;
}

const render = (map) =>
  [...map.keys()]
    .sort()
    .map(
      (k) =>
        `  ${JSON.stringify(k)}: ${JSON.stringify([...map.get(k)].sort())},`
    )
    .join("\n");

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/build-nicknames.mjs. Do not edit by hand.
 *
 * Derived from https://github.com/carltonnorthern/nicknames, Apache-2.0. The
 * source CSV and its licence are vendored under \`data/\`.
 *
 * ${pairs} pairs, ${edges.size} names; ${parents.size} of them have a credible
 * formal parent (${pruned} rows pruned as reversed).
 *
 * ONE HOP ONLY. See the generator's header for what the transitive closure of
 * this relation does (it makes John and Robert the same person).
 */

/** Every name the source pairs this one with, in either direction. */
export const NICKNAME_EDGES: Record<string, string[]> = {
${render(edges)}
};

/**
 * Diminutive -> the formal given names it credibly stands for. Used ONLY to ask
 * whether two diminutives share a formal name (jim and jimmy are both James).
 */
export const NICKNAME_PARENTS: Record<string, string[]> = {
${render(parents)}
};
`
);

console.log(
  `${pairs} pairs -> ${edges.size} names, ${parents.size} with parents, ${pruned} reversed rows pruned -> ${path.relative(ROOT, OUT)}`
);
